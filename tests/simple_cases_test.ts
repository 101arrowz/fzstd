Deno.test("Decompression of 1 000 000 nuls", () => {
  const data = [
    0x28, 0xB5, 0x2F, 0xFD, 0xA4, 0x40, 0x42, 0x0F, 0x00, 0x54, 0x00, 0x00,
    0x10, 0x00, 0x00, 0x01, 0x00, 0xFB, 0xFF, 0x39, 0xC0, 0x02, 0x02, 0x00,
    0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00,
    0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x02, 0x00, 0x10, 0x00, 0x03, 0x12,
    0x0A, 0x00, 0xCC, 0xAE, 0xCA, 0x39
  ];
  const compressed = new Uint8Array(data);
  const decompressed : Uint8Array = fzstd.decompress(compressed);
  const arraySum = decompressed.reduce((accumulator, currentValue) => accumulator + currentValue);
  assertEquals(1_000_000, decompressed.length);
  assertEquals(0, arraySum);
});

Deno.test("Decompression of two frames into an output buffer", () => {
  const data = [
    0x28, 0xB5, 0x2F, 0xFD, 0x24, 0x3B, 0x55, 0x00, 0x00, 0x20, 0x4F, 0x6B,
    0x20, 0x4F, 0x01, 0x00, 0xF4, 0x74, 0x44, 0x96, 0x2E, 0xDD, 0xB4, 0x28,
    0xB5, 0x2F, 0xFD, 0x24, 0x37, 0x25, 0x01, 0x00, 0xF0, 0x4C, 0x6F, 0x72,
    0x65, 0x6D, 0x20, 0x69, 0x70, 0x73, 0x75, 0x6D, 0x20, 0x64, 0x6F, 0x6C,
    0x6F, 0x72, 0x20, 0x73, 0x69, 0x74, 0x20, 0x61, 0x6D, 0x65, 0x74, 0x2C,
    0x20, 0x6C, 0x2E, 0x01, 0x00, 0xFD, 0x32, 0x9D, 0x66, 0x55, 0x98, 0x26
  ];
  const compressed = new Uint8Array(data);
  const expected = "Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok Ok" +
    "Lorem ipsum dolor sit amet, lorem ipsum dolor sit amet.";
  assertEquals(expected, new TextDecoder().decode(fzstd.decompress(compressed)));
  const buf = new Uint8Array(expected.length);
  const decompressed = fzstd.decompress(compressed, buf);
  assertEquals(buf, decompressed);
  assertEquals(expected, new TextDecoder().decode(decompressed));
});
